function productData(category, variant) {
  const colors = [
    'Midnight Blue',
    'Graphite',
    'Arctic White',
    'Forest Green',
    'Sand',
  ];
  const code = `${String(categories.indexOf(category) + 1).padStart(2, '0')}${variant + 1}`;
  const specifications = {
    Model: `DEMO-${code}`,
    ...category.specifications,
    Color: colors[variant],
    Series: `Demo Series ${variant + 1}`,
    Package: 'Retail demonstration pack',
    Warranty: 'Demo data only - confirm actual terms with the store',
    Dataset: 'APPLIANCES-DEMO-V1',
  };
  return {
    name: `Demo ${category.singular} ${code}`,
    SKU: `DEMO-V1-${code}`,
    brand: variant % 2 ? 'Nova Demo' : 'Aster Demo',
    subtitle: `Series ${variant + 1} - ${colors[variant]}`,
    price: Math.round((category.price * (1 + variant * 0.08)) / 10) * 10,
    stockQty: variant === 4 ? 0 : 10 + variant * 5,
    description: `This is a demonstration ${category.singular.toLowerCase()} from the Appliances.lk sample catalog. The specifications, price, brand, and illustration are fictional development data, not manufacturer claims. The ${colors[variant].toLowerCase()} finish and category-specific features let you explore product comparisons, image galleries, and checkout behavior. Replace this item with a verified supplier listing before offering it for sale.`,
    features: Object.entries(category.specifications)
      .slice(0, 7)
      .map(
        ([key, value]) =>
          `${key.replace(/([a-z])([A-Z])/g, '$1 $2')}: ${value}`,
      ),
    boxContents: category.boxContents,
    warranty:
      'Demonstration entry: no real warranty or availability is implied.',
    specifications,
    badge: variant === 0 ? 'NEW' : variant === 2 ? 'DEAL' : null,
  };
}
